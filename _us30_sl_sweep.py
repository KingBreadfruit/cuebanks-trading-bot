"""
_us30_sl_sweep.py
Sweep SL multipliers for US30 to test the "wide SL helps" hypothesis.
For each (sl_mult, tp_mult) combo:
  1. Re-label US30 with that triple-barrier
  2. Train + WF (5 folds, 5-seed ensemble, tuned params)
  3. Backtest with matching SL/TP in the engine
  4. Report mean Sharpe + win + DD + profitable folds
Picks winner by mean Sharpe.

Configs tested (R:R kept at 1:2 to give the wider stop a real shot):
  1.5 / 3.0   (baseline — what we're running now)
  2.0 / 4.0   (33% wider)
  2.5 / 5.0   (67% wider)
"""
import contextlib
import io
import json
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from backtest.engine import Backtester
from features.smc_features import (
    FEATURE_COLS, build_features, create_labels,
)
from models.gbdt_model import SMCTraderGBDT
from walkforward import _load_tuned, N_FOLDS, WARMUP_FRAC


SYMBOL = "US30"
CONFIGS = [
    (1.5, 3.0),  # baseline
    (2.0, 4.0),  # 33% wider, R:R kept at 1:2
    (2.5, 5.0),  # 67% wider, R:R kept at 1:2
]


def _features_with_custom_labels(sl_mult: float, tp_mult: float) -> pd.DataFrame:
    """Build US30 features then OVERWRITE the label column with custom-mult
    triple-barrier labels."""
    raw_m15 = pd.read_csv(f"data/raw/{SYMBOL}_M15.csv",
                          index_col=0, parse_dates=True)
    raw_h4  = pd.read_csv(f"data/raw/{SYMBOL}_H4.csv",
                          index_col=0, parse_dates=True)
    df = build_features(raw_m15, df_h4=raw_h4)
    # Overwrite labels generated by build_features (which used the defaults).
    relabelled = create_labels(df, atr_tp_mult=tp_mult, atr_sl_mult=sl_mult)
    df["label"] = relabelled["label"].values
    df = df.dropna(subset=FEATURE_COLS + ["label"])
    return df


def run_wf_for_config(sl_mult: float, tp_mult: float) -> dict:
    print(f"\n{'='*68}")
    print(f"  Config: sl_mult={sl_mult}  tp_mult={tp_mult}  (R:R 1:{tp_mult/sl_mult:.1f})")
    print(f"{'='*68}")

    params = _load_tuned(SYMBOL)
    df = _features_with_custom_labels(sl_mult, tp_mult)
    n = len(df)
    warmup_end = int(n * WARMUP_FRAC)
    test_size = (n - warmup_end) // N_FOLDS
    print(f"  Bars: {n:,}  warmup: {warmup_end:,}  test/fold: {test_size:,}")

    fold_metrics = []
    for k in range(N_FOLDS):
        train_end  = warmup_end + k * test_size
        test_start = train_end
        test_end   = min(train_end + test_size, n)
        if test_end - test_start < 100:
            break

        df_train = df.iloc[:train_end].copy()
        df_test  = df.iloc[test_start:test_end].copy()

        trader = SMCTraderGBDT(**params, n_seeds=5)
        with contextlib.redirect_stdout(io.StringIO()):
            trader.train(df_train, FEATURE_COLS, val_split=0.2,
                         save_path=f"models/saved/_sl_sweep_tmp/{SYMBOL}")
            df_pred = trader.predict(df_test)

        bt = Backtester(initial_capital=10_000, prime_only=True,
                        sl_atr_mult=sl_mult, tp_atr_mult=tp_mult)
        with contextlib.redirect_stdout(io.StringIO()):
            m = bt.run(df_pred)

        if "error" in m:
            fold_metrics.append({"trades": 0, "win": 0, "ret": 0, "sharpe": 0, "dd": 0})
        else:
            fold_metrics.append({
                "trades": m["total_trades"],
                "win":    m["win_rate"],
                "ret":    m["total_return"],
                "sharpe": m["sharpe_ratio"],
                "dd":     m["max_drawdown"],
            })
        a = fold_metrics[-1]
        print(f"  fold {k}: trades={a['trades']:>4} win={a['win']:>5.1f}% "
              f"ret={a['ret']:>7.1f}% sharpe={a['sharpe']:>5.2f} dd={a['dd']:>6.1f}%")

    df_m = pd.DataFrame(fold_metrics)
    summary = {
        "sl_mult":         sl_mult,
        "tp_mult":         tp_mult,
        "n_folds":         len(df_m),
        "trades_mean":     float(df_m["trades"].mean()),
        "win_mean":        float(df_m["win"].mean()),
        "return_mean":     float(df_m["ret"].mean()),
        "sharpe_mean":     float(df_m["sharpe"].mean()),
        "sharpe_std":      float(df_m["sharpe"].std()),
        "dd_mean":         float(df_m["dd"].mean()),
        "profitable_folds": int((df_m["ret"] > 0).sum()),
    }
    print(f"  AGGREGATE: sharpe {summary['sharpe_mean']:.2f}±{summary['sharpe_std']:.2f}  "
          f"win {summary['win_mean']:.1f}%  ret {summary['return_mean']:.1f}%  "
          f"dd {summary['dd_mean']:.1f}%  profit_folds {summary['profitable_folds']}/{summary['n_folds']}")
    return summary


def main():
    results = []
    for sl, tp in CONFIGS:
        r = run_wf_for_config(sl, tp)
        results.append(r)

    print(f"\n\n{'#'*68}")
    print(f"  US30 SL SWEEP — FINAL COMPARISON")
    print(f"{'#'*68}\n")
    print(f"  {'sl_mult':>7} {'tp_mult':>7} {'sharpe':>10} {'win%':>6} {'trades':>7} {'ret%':>7} {'dd%':>7} {'profit folds':>12}")
    for r in sorted(results, key=lambda x: -x["sharpe_mean"]):
        print(f"  {r['sl_mult']:>7.1f} {r['tp_mult']:>7.1f} "
              f"{r['sharpe_mean']:>5.2f}±{r['sharpe_std']:>.2f}  {r['win_mean']:>5.1f}% "
              f"{int(r['trades_mean']):>7} {r['return_mean']:>6.1f}% {r['dd_mean']:>6.1f}%  "
              f"{r['profitable_folds']:>5}/{r['n_folds']}")

    winner = max(results, key=lambda x: x["sharpe_mean"])
    print(f"\n  Winner: sl={winner['sl_mult']} tp={winner['tp_mult']} -> sharpe {winner['sharpe_mean']:.2f}")
    with open("models/saved/_sl_sweep_tmp/US30_sl_sweep.json", "w") as f:
        json.dump(results, f, indent=2)


if __name__ == "__main__":
    os.makedirs("models/saved/_sl_sweep_tmp", exist_ok=True)
    main()
